/** Мінімальна добова норма пиття на людину, л (Sphere: 2,5–3). */
export const DRINK_PER_DAY = 3;

/**
 * Попередження за поточним станом. Пороги температури — за оглядом PHE
 * (18 °C — мінімальний ризик; <16 — дихальні ризики; 9–12 — серце й судини; ≤5 — високий ризик переохолодження).
 * @param {Ctx} ctx
 * @returns {Alert[]}
 */
export function stateAlerts(ctx) {
  /** @type {Alert[]} */
  const out = [];
  const t = ctx.roomC;
  if (t != null && Number.isFinite(t)) {
    if (t <= 5) {
      out.push({ id: 'cold5', level: 'danger', need: 'heat', title: `У приміщенні ${fmtC(t)}`, text: 'Температура +5 °C і нижче — високий ризик переохолодження (PHE). Зберіть усіх у теплій зоні та переходьте в опалюване місце, щойно це безпечно.', action: 'heat-relocate', sources: ['phe', 'cdcWinter'] });
    } else if (t < 9) {
      out.push({ id: 'cold8', level: 'danger', need: 'heat', title: `У приміщенні ${fmtC(t)}`, text: 'Дуже холодно — нижче діапазону 9–12 °C, де вже зростають ризики для серця й судин (PHE). Тепла зона, сухий одяг і план переходу в опалюване місце.', action: 'heat-relocate', sources: ['phe', 'cdcWinter'] });
    } else if (t <= 12) {
      out.push({ id: 'cold12', level: ctx.vulnerable ? 'danger' : 'caution', need: 'heat', title: `У приміщенні ${fmtC(t)}`, text: 'При 9–12 °C зростає навантаження на серце й судини (PHE). Створіть теплу зону й стежте за самопочуттям; для дітей, літніх і хворих людей плануйте перехід у тепле місце.', action: 'heat-room', sources: ['phe'] });
    } else if (t < 16) {
      out.push({ id: 'cold16', level: 'caution', need: 'heat', title: `У приміщенні ${fmtC(t)}`, text: 'Нижче 16 °C знижується опір респіраторним інфекціям (PHE). Багатошаровий одяг і тепла зона.', action: 'heat-room', sources: ['phe'] });
    } else if (t < 18) {
      out.push({ id: 'cold18', level: 'info', need: 'heat', title: `У приміщенні ${fmtC(t)}`, text: 'Трохи нижче рекомендованих 18 °C (PHE). Вдягніться тепліше, особливо літнім людям.', action: 'heat-layers', sources: ['phe'] });
    }
    if (t >= 35) {
      out.push({ id: 'hot35', level: 'danger', need: 'cool', title: `У приміщенні ${fmtC(t)}`, text: 'За такої спеки вентилятор не захищає від теплового удару (CDC). Прохолодний душ, вода, прохолодніше місце; стежте за ознаками перегрівання.', action: 'cool-alert', sources: ['cdcHeat'] });
    } else if (t >= 30) {
      out.push({ id: 'hot30', level: 'caution', need: 'cool', title: `У приміщенні ${fmtC(t)}`, text: 'Спекотно. Затініть вікна, пийте воду, охолоджуйте тіло вологою.', action: 'cool-body', sources: ['cdcHeat'] });
    }
  }

  if (ctx.waterL != null && Number.isFinite(ctx.waterL) && ctx.n > 0) {
    const day = ctx.n * DRINK_PER_DAY;
    if (ctx.waterL < day && ctx.tap === true) {
      out.push({ id: 'water1', level: 'caution', need: 'water', title: `Питної води ${fmtL(ctx.waterL)}`, text: `Менше ніж на добу пиття для ${ctx.n} ${people(ctx.n)}, але вода з крана є. Наберіть запас у чисті ємності з кришками, поки подача не зникла; якщо є сумнів щодо якості — кип’ятіть.`, action: 'water-store', sources: ['sphere', 'readyWater'] });
    } else if (ctx.waterL < day) {
      out.push({ id: 'water1', level: 'danger', need: 'water', title: `Питної води ${fmtL(ctx.waterL)}`, text: `Менше ніж на добу пиття для ${ctx.n} ${people(ctx.n)} (≈${DRINK_PER_DAY} л на людину). Пріоритет — пиття; шукайте приховані запаси й безпечні джерела.`, action: 'water-hidden', sources: ['sphere', 'readyWater'] });
    } else if (ctx.waterL < day * 3) {
      out.push({ id: 'water3', level: ctx.tap === true ? 'info' : 'caution', need: 'water', title: `Питної води ${fmtL(ctx.waterL)}`, text: `Вистачить на пиття менше ніж на 3 доби для ${ctx.n} ${people(ctx.n)}. Розподіліть запас і економте воду в побуті.`, action: 'water-calc', sources: ['sphere', 'readyWater'] });
    }
  }

  if (ctx.batteryPct != null && Number.isFinite(ctx.batteryPct) && ctx.batteryPct <= 20 && !ctx.power) {
    out.push({ id: 'batt', level: 'caution', need: 'energy', title: `Заряд ${Math.round(ctx.batteryPct)} %`, text: 'Заряду мало. Залиште його на зв’язок і світло, увімкніть енергозбереження.', action: 'energy-phone', sources: ['cdcOutage'] });
  }

  const combustion = ctx.equip.has('burner') || ctx.equip.has('stove') || ctx.gas;
  if (combustion && !ctx.equip.has('coAlarm')) {
    out.push({ id: 'coalarm', level: 'info', need: 'general', title: 'Немає детектора чадного газу', text: 'Вдома є газ, піч чи пальник. Детектор чадного газу на батарейках попередить про небезпеку, яку неможливо відчути (CDC).', action: 'prep-co', sources: ['cdcCO'] });
  }

  const order = { danger: 0, caution: 1, info: 2 };
  return out.sort((a, b) => order[a.level] - order[b.level]);
}

/** @param {number} t */
function fmtC(t) {
  const r = Math.round(t * 10) / 10;
  return `${r > 0 ? '+' : ''}${String(r).replace('.', ',')} °C`;
}
/** @param {number} l */
function fmtL(l) {
  return `${String(Math.round(l * 10) / 10).replace('.', ',')} л`;
}
/** @param {number} n */
function people(n) {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return 'людини';
  return 'людей';
}
