/* ───────────── Міні-моделі для інтерактивних карток (ілюстративні) ───────────── */

/** Енергія у Вт·год. */
export function jouleWh(watts, hours) {
  return Math.max(0, watts) * Math.max(0, hours);
}

/** Години обертання ручного генератора, щоб дати телефону energyWh (ілюстрація). */
export function faradayHours(crankW, energyWh = 15, eff = 0.6) {
  if (!(crankW > 0)) return Infinity;
  return energyWh / (crankW * eff);
}

/** Ідеальний ККД Карно, частка 0..1. Температури в °C. */
export function carnotEta(hotC, coldC) {
  const th = hotC + 273.15;
  const tc = coldC + 273.15;
  if (!(th > tc) || tc <= 0) return 0;
  return 1 - tc / th;
}

/**
 * Відносні тепловтрати (1 = базові) при зміні площі та додаванні утеплення.
 * Ілюстративна модель: R0 — опір наявної огорожі, k — теплопровідність утеплювача.
 */
export function fourierRelative(areaFactor, addCm, r0 = 0.5, k = 0.04) {
  const rAdd = Math.max(0, addCm) / 100 / k;
  return Math.max(0, areaFactor) * (r0 / (r0 + rAdd));
}

/** Температура за законом охолодження Ньютона. */
export function newtonTemp(t0, tEnv, hours, tauHours) {
  if (!(tauHours > 0)) return tEnv;
  return tEnv + (t0 - tEnv) * Math.exp(-Math.max(0, hours) / tauHours);
}

