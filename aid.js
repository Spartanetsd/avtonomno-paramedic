/**
 * Хронометр реанімації: «хв:сс».
 * @param {number} s секунди
 */
export function clock(s) {
  const t = Math.max(0, Math.floor(s));
  return `${Math.floor(t / 60)}:${String(t % 60).padStart(2, '0')}`;
}

/**
 * Стан метронома в момент натискання № n (від 1): номер у циклі й чи час на вдихи.
 * @param {number} n порядковий номер натискання від початку
 * @param {boolean} breaths режим 30:2
 */
export function cprBeat(n, breaths) {
  const k = ((Math.max(1, Math.floor(n)) - 1) % CPR_PUSHES) + 1;
  return { k, breathe: breaths && k === CPR_PUSHES };
}

/** Інтервал між натисканнями, мс. */
export function cprInterval(rate = CPR_RATE) {
  return 60000 / rate;
}
